#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Dither {
    pub index: usize,
    pub invert: bool,
    pub flip_x: bool,
    pub flip_y: bool,
    /// Pattern phase starts at the stroke's first pixel instead of the canvas origin.
    pub anchored: bool,
}

impl Default for Dither {
    fn default() -> Self {
        Dither { index: 0, invert: false, flip_x: false, flip_y: false, anchored: false }
    }
}

impl Dither {
    /// Pattern width in logical pixels.
    pub fn width(mode: Mode) -> usize {
        match mode {
            Mode::Hires => 8,
            Mode::Multicolor => 4,
        }
    }

    /// True if pattern cell (x, y) is set, after flips and inversion.
    /// `x` is in 0..width(mode), `y` in 0..8.
    pub fn cell(&self, mode: Mode, x: usize, y: usize) -> bool {
        let w = Self::width(mode);
        let x = if self.flip_x { w - 1 - x } else { x };
        let y = if self.flip_y { 7 - y } else { y };
        let idx = self.index.min(COUNT - 1);
        let on = match mode {
            Mode::Hires => (HR[idx][y] >> (7 - x)) & 1 == 1,
            Mode::Multicolor => (MC[idx][y] >> (6 - 2 * x)) & 3 == 3,
        };
        // The solid pattern is never inverted (it would block all painting).
        if self.invert && idx != 0 { !on } else { on }
    }

    /// Whether the pixel at (x, y) may be painted, with the pattern phase at `origin`.
    pub fn allows(&self, mode: Mode, x: i32, y: i32, origin: (i32, i32)) -> bool {
        let w = Self::width(mode) as i32;
        let lx = (x - origin.0).rem_euclid(w) as usize;
        let ly = (y - origin.1).rem_euclid(8) as usize;
        self.cell(mode, lx, ly)
    }

    /// True when the pattern paints every pixel (no filtering needed).
    pub fn is_solid(&self) -> bool {
        self.index == 0
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn solid_paints_everywhere_even_inverted() {
        let d = Dither { invert: true, ..Default::default() };
        for y in 0..8 {
            for x in 0..8 {
                assert!(d.cell(Mode::Hires, x, y));
            }
        }
    }

    #[test]
    fn checkerboard_alternates() {
        let d = Dither { index: 8, ..Default::default() }; // $55,$aa rows
        assert_ne!(d.allows(Mode::Hires, 0, 0, (0, 0)), d.allows(Mode::Hires, 1, 0, (0, 0)));
        assert_ne!(d.allows(Mode::Hires, 0, 0, (0, 0)), d.allows(Mode::Hires, 0, 1, (0, 0)));
    }

    #[test]
    fn invert_complements() {
        for i in 1..COUNT {
            let a = Dither { index: i, ..Default::default() };
            let b = Dither { invert: true, ..a };
            for y in 0..8 {
                for x in 0..4 {
                    assert_ne!(a.cell(Mode::Multicolor, x, y), b.cell(Mode::Multicolor, x, y));
                }
            }
        }
    }

    #[test]
    fn flips_mirror_pattern() {
        let a = Dither { index: 24, ..Default::default() }; // diagonal
        let f = Dither { flip_x: true, ..a };
        for y in 0..8 {
            for x in 0..8 {
                assert_eq!(a.cell(Mode::Hires, x, y), f.cell(Mode::Hires, 7 - x, y));
            }
        }
    }

    #[test]
    fn anchor_shifts_phase() {
        let d = Dither { index: 8, ..Default::default() };
        let at = |o| d.allows(Mode::Hires, 3, 3, o);
        assert_ne!(at((0, 0)), at((1, 0)));
        assert_eq!(d.allows(Mode::Hires, -1, -1, (0, 0)), d.allows(Mode::Hires, 7, 7, (0, 0)));
    }

    #[test]
    fn multicolor_patterns_are_pairs_only() {
        for p in MC.iter() {
            for b in p {
                for k in 0..4 {
                    let v = (b >> (6 - 2 * k)) & 3;
                    assert!(v == 0 || v == 3);
                }
            }
        }
    }
}
